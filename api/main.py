"""FastAPI service for breast cancer survival risk.

Endpoints:
  GET  /health   -> is the service ready (model loaded)?
  POST /predict  -> risk prediction for one patient (also logged to the DB)
  GET  /docs     -> interactive documentation (generated by FastAPI)

Run from the project root (with `mlflow server` running):
    python -m uvicorn api.main:app --reload
"""
from contextlib import asynccontextmanager

import mlflow
import mlflow.sklearn
import pandas as pd
from fastapi import FastAPI, HTTPException
from fastapi.responses import JSONResponse
from mlflow import MlflowClient

from api.db import PredictionLog, SessionLocal, init_db
from api.schemas import PatientFeatures, PredictionResponse

# Reuse the names from training, so the API always loads what train.py registered.
from src.train import CHAMPION_ALIAS, REGISTERED_MODEL_NAME, TRACKING_URI

# "models:/<name>@<alias>" = whichever version the champion alias points to.
# Moving the alias in MLflow (and restarting the API) deploys or rolls back a
# model with no code change.
MODEL_URI = f"models:/{REGISTERED_MODEL_NAME}@{CHAMPION_ALIAS}"

# Probability at or above which we predict "Dead". 0.5 is the default; it is
# the same cut-off the training metrics (recall 0.63) were measured at.
THRESHOLD = 0.5


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Runs once when the API starts (code before `yield`) and stops (after).

    Loading the model here, not inside /predict, means it is downloaded and
    deserialised once instead of on every request (that would take seconds).
    """
    init_db()  # create the predictions table if it doesn't exist
    mlflow.set_tracking_uri(TRACKING_URI)

    # app.state = a place to keep objects shared by all requests.
    app.state.model = None
    app.state.model_version = None
    app.state.model_error = None
    try:
        # mlflow.sklearn (not mlflow.pyfunc) returns the real scikit-learn
        # Pipeline, which has predict_proba(); pyfunc only gives 0/1 labels.
        app.state.model = mlflow.sklearn.load_model(MODEL_URI)
        # Look up which version number the alias points to (for the response
        # and the log). MLflow returns an int, our schema wants a string.
        version = MlflowClient().get_model_version_by_alias(
            REGISTERED_MODEL_NAME, CHAMPION_ALIAS
        ).version
        app.state.model_version = str(version)
    except Exception as exc:
        # Don't crash: start anyway and let /health report the problem
        # (e.g. MLflow server not running, or no model registered yet).
        app.state.model_error = str(exc)

    yield  # the API serves requests while paused here


app = FastAPI(
    title="Breast Cancer Survival API",
    description="Predicts the risk of death for breast cancer patients (SEER data).",
    version="1.0.0",
    lifespan=lifespan,
)


@app.get("/health")
def health():
    """Readiness check, used by Docker, Jenkins smoke tests and load balancers.

    200 = ready to serve; 503 (Service Unavailable) = running but the model
    isn't loaded, so traffic shouldn't be sent here yet.
    """
    body = {
        "status": "ok" if app.state.model is not None else "unavailable",
        "model_loaded": app.state.model is not None,
        "model_uri": MODEL_URI,
        "model_version": app.state.model_version,
    }
    if app.state.model is None:
        body["error"] = app.state.model_error
        return JSONResponse(status_code=503, content=body)
    return body


# response_model: FastAPI checks the output matches PredictionResponse and
# shows that format in /docs.
# Plain `def` (not `async def`): scikit-learn and SQLAlchemy calls are
# blocking, so FastAPI runs this in a worker thread and other requests aren't
# held up.
@app.post("/predict", response_model=PredictionResponse)
def predict(patient: PatientFeatures):
    """Predict for one patient. FastAPI has already validated `patient`
    against PatientFeatures; invalid input never reaches this code (HTTP 422).
    """
    if app.state.model is None:
        raise HTTPException(status_code=503, detail="Model not loaded")

    # One-row DataFrame with the training column names ("T Stage", ...).
    # The Pipeline does all preprocessing (scaling, encoding) itself,
    # exactly as in training, so there is no training/serving skew.
    X = pd.DataFrame([patient.model_dump(by_alias=True)])

    # predict_proba -> [[P(Alive), P(Dead)]]; take P(Dead) for the first row.
    probability_dead = float(app.state.model.predict_proba(X)[0, 1])
    prediction = "Dead" if probability_dead >= THRESHOLD else "Alive"

    # Log inputs + output. model_dump() (no aliases) gives snake_case keys,
    # which match PredictionLog's column names. `with` closes the session
    # even if something fails.
    with SessionLocal() as session:
        session.add(
            PredictionLog(
                **patient.model_dump(),
                prediction=prediction,
                probability_dead=probability_dead,
                model_version=app.state.model_version,
            )
        )
        session.commit()

    return PredictionResponse(
        prediction=prediction,
        probability_dead=round(probability_dead, 4),
        model_version=app.state.model_version,
    )